package gr.aueb.cf.java.ch5;

/**
 * Demonstrates variable declarations
 */
public class Declarations {

    public static void main(String[] args) {
        float myFloat = 1.2345f ;   //type suffix double -> float
        double myDouble = 1.2345678910;

        System.out.printf("myFloat: %f\nmyDouble: %.10f", myFloat , myDouble);
    }
}
